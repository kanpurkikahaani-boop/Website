/**
 * Builds the Navaratri post from content/blogs/ and writes
 * supabase/migrations/0007_publish_navaratri.sql (idempotent; paste into the Supabase SQL editor).
 *   npm run build:navaratri
 */
import { readFileSync, writeFileSync } from "node:fs";
import { generateHTML, generateJSON } from "@tiptap/html/server";
import { navaratriPost as P } from "../content/blogs/navaratri-in-kanpur.meta";
import { blogExtensions } from "../src/lib/content/extensions";
import { enrichArticleHtml } from "../src/lib/content/enrich";
import { htmlToText, readingMinutes, sanitizeBlogHtml } from "../src/lib/content/sanitize";

export function buildNavaratri() {
  const source = readFileSync("content/blogs/navaratri-in-kanpur.html", "utf8").replace(/<!--[\s\S]*?-->/g, "").trim();
  const doc = generateJSON(source, blogExtensions);
  const html = sanitizeBlogHtml(enrichArticleHtml(generateHTML(doc, blogExtensions))).replace(/<p>\s*<\/p>/g, "");
  const minutes = readingMinutes(htmlToText(html.replace(/<span class="sr-only">[^<]*<\/span>/g, "")));
  return { doc, html, minutes };
}

const q = (s: string) => `$kkk$${s}$kkk$`;
const j = (v: unknown) => `${q(JSON.stringify(v))}::jsonb`;

if (process.argv[1]?.includes("build-navaratri-post")) {
  const { doc, html, minutes } = buildNavaratri();
  const sql = `-- Publishes "${P.title}" by ${P.author.name}.
-- Generated by scripts/build-navaratri-post.ts — do not edit by hand. Safe to re-run.
-- Run after 0006_authors_and_post_fields.sql.

insert into public.authors (slug, name, bio)
values (${q(P.author.slug)}, ${q(P.author.name)}, ${q(P.author.bio)})
on conflict (slug) do nothing;

insert into public.posts (
  slug, title, title_emphasis, excerpt, standfirst, content_json, content_html,
  cover_url, cover_alt, cover_caption, cover_credit, city, category, tags,
  seo_title, seo_description, pull_quote, key_facts, plan_visit, glossary, further_reading,
  status, published_at, reading_minutes, author, author_id
) values (
  ${q(P.slug)}, ${q(P.title)}, ${q(P.titleEmphasis)}, ${q(P.excerpt)}, ${q(P.excerpt)},
  ${j(doc)}, ${q(html)},
  ${q(P.cover.url)}, ${q(P.cover.alt)}, ${q(P.cover.caption)}, ${P.cover.credit ? q(P.cover.credit) : "null"},
  ${q(P.city)}, ${q(P.category)}, array[${P.tags.map((t) => `'${t}'`).join(", ")}]::text[],
  ${q(P.seoTitle)}, ${q(P.seoDescription)}, ${q(P.pullQuote)},
  ${j(P.keyFacts)}, ${j(P.planVisit)}, ${j(P.glossary)}, ${j(P.furtherReading)},
  'published', '${P.publishedAt}', ${minutes}, ${q(P.author.name)},
  (select id from public.authors where slug = ${q(P.author.slug)})
)
on conflict (slug) do update set
  title = excluded.title, title_emphasis = excluded.title_emphasis, excerpt = excluded.excerpt,
  standfirst = excluded.standfirst, content_json = excluded.content_json, content_html = excluded.content_html,
  cover_url = excluded.cover_url, cover_alt = excluded.cover_alt, cover_caption = excluded.cover_caption,
  cover_credit = excluded.cover_credit, city = excluded.city, category = excluded.category, tags = excluded.tags,
  seo_title = excluded.seo_title, seo_description = excluded.seo_description, pull_quote = excluded.pull_quote,
  key_facts = excluded.key_facts, plan_visit = excluded.plan_visit, glossary = excluded.glossary,
  further_reading = excluded.further_reading, status = excluded.status, published_at = excluded.published_at,
  reading_minutes = excluded.reading_minutes, author = excluded.author, author_id = excluded.author_id;

-- Refresh the Supabase API's schema cache, then show the result (expect 1 row: published).
notify pgrst, 'reload schema';
select p.slug, p.status, p.published_at, a.name as author
from public.posts p left join public.authors a on a.id = p.author_id
where p.slug = ${q(P.slug)};
`;
  writeFileSync("supabase/migrations/0007_publish_navaratri.sql", sql);
  const links = [...html.matchAll(/<a [^>]*href="([^"]+)"/g)].length;
  console.log(`wrote 0007_publish_navaratri.sql — ${minutes} min read, ${links} inline links, ${html.length} chars of HTML`);
}
