/**
 * npm run images:verify — runs before every build (prebuild). Fails if any manifest photo:
 *  - is missing licence, author or source URL (non-own photos), or an AI-check note;
 *  - has a licence outside the allowed list (PD, CC0, CC BY, CC BY-SA, Unsplash, Pexels; never NC/ND);
 *  - is below the minimum resolution of a slot it fills;
 *  - has empty alt text;
 *  - points to a missing local file, or the file's real size differs from the manifest;
 *  - is used in more than one slot on the same page;
 *  - carries an AI flag / AI keywords.
 * Also: package.json must not contain AI image tools, and team photos must match team.ts.
 */
import { existsSync, readFileSync } from "node:fs";
import path from "node:path";
import { photos, type Photo } from "../../src/data/images";
import { portraitAlt, team } from "../../src/data/team";
import { collectSlots } from "./slots";

const AI_WORDS = /\b(ai[- ]?generated|generated by ai|midjourney|dall[·.\- ]?e|stable[- ]diffusion|firefly|imagen|generative|upscal(ed|er|ing)|gfpgan|real-?esrgan|topaz|digital art|cgi|3d render)\b/i;
const AI_PACKAGES = /(replicate|@fal-ai|stability|openai|@google\/generative|upscal|esrgan|background-removal|remove\.?bg|rembg|gfpgan|@imgly)/i;

function licenceOk(p: Photo): string | null {
  const l = p.license.trim();
  if (/\bNC\b|\bND\b|non-?commercial|no-?deriv|fair use/i.test(l)) return `licence "${l}" is NC/ND/fair use — not allowed`;
  switch (p.source) {
    case "own":
      return /Kanpur Ki Kahaani team/.test(l) ? null : `own photo needs the team licence line`;
    case "unsplash":
      return /^Unsplash License$/i.test(l) ? null : `Unsplash photos must be "Unsplash License"`;
    case "pexels":
      return /^Pexels License$/i.test(l) ? null : `Pexels photos must be "Pexels License"`;
    case "wikimedia":
    case "flickr":
      return /^(Public domain|PDM|CC0( 1\.0)?|CC BY( \d\.\d)?|CC BY-SA( \d\.\d)?)$/i.test(l) ? null : `licence "${l}" not in PD / CC0 / CC BY / CC BY-SA`;
  }
}

function realSize(file: string): { width: number; height: number } | null {
  const d = readFileSync(file);
  if (d.subarray(1, 4).toString() === "PNG") return { width: d.readUInt32BE(16), height: d.readUInt32BE(20) };
  if (d[0] === 0xff && d[1] === 0xd8) {
    let i = 2;
    while (i < d.length) {
      if (d[i] !== 0xff) { i++; continue; }
      const m = d[i + 1];
      if (m >= 0xc0 && m <= 0xcf && ![0xc4, 0xc8, 0xcc].includes(m)) return { height: d.readUInt16BE(i + 5), width: d.readUInt16BE(i + 7) };
      i += 2 + d.readUInt16BE(i + 2);
    }
  }
  return null;
}

const problems: string[] = [];
const bad = (key: string, msg: string) => problems.push(`${key}: ${msg}`);

for (const [key, p] of Object.entries(photos)) {
  if (!p.alt?.trim()) bad(key, "empty alt text");
  const lic = licenceOk(p);
  if (lic) bad(key, lic);
  if (p.source !== "own") {
    if (!p.author?.trim()) bad(key, "no author");
    if (!p.sourcePageUrl?.startsWith("https://")) bad(key, "no source page URL");
    if ((p.source === "wikimedia" || p.source === "flickr") && !p.licenseUrl?.startsWith("https://")) bad(key, "no licence URL");
    if (!p.aiCheck?.trim()) bad(key, "no aiCheck note (evidence it's a real photo)");
    if (p.representative && !/representative image/i.test(p.caption ?? "")) bad(key, 'representative photo must say "Representative image" in its caption');
  }
  for (const field of [p.subject, p.alt, p.caption, p.author, p.relevanceNote]) if (field && AI_WORDS.test(field)) bad(key, `AI keyword in metadata: "${field}"`);
  if (p.src.startsWith("/")) {
    const file = path.join(process.cwd(), "public", p.src);
    if (!existsSync(file)) bad(key, `missing file ${p.src}`);
    else {
      const s = realSize(file);
      if (s && (s.width !== p.width || s.height !== p.height)) bad(key, `file is ${s.width}×${s.height}, manifest says ${p.width}×${p.height}`);
    }
  } else if (!/^https:\/\/images\.unsplash\.com\//.test(p.src)) bad(key, "remote src must be images.unsplash.com (everything else is stored locally)");
  else if (p.source !== "unsplash") bad(key, "only Unsplash photos may be hotlinked");
}

// Slot rules: resolution per slot, no photo twice on one page.
const slots = collectSlots();
const seen = new Map<string, string>();
// Even before photos exist: two slots on one page must not point at the same image.
const keys = new Map<string, string>();
for (const s of slots) {
  const k = `${s.page}::${s.currentImage}`;
  if (keys.has(k)) problems.push(`${s.currentImage}: slots ${keys.get(k)} and ${s.slotId} on ${s.page} share one image — give one its own path`);
  keys.set(k, s.slotId);
}
for (const s of slots) {
  const p = photos[s.currentImage];
  if (!p) continue;
  if (p.width < s.minWidth) bad(s.currentImage, `${p.width}px wide — slot ${s.slotId} needs ≥ ${s.minWidth}px`);
  if (p.representative && !s.representativeOk) bad(s.currentImage, `slot ${s.slotId} must show the exact place, not a representative image`);
  const k = `${s.page}::${p.src}`;
  if (seen.has(k) && seen.get(k) !== s.slotId) bad(s.currentImage, `used twice on ${s.page} (${seen.get(k)} and ${s.slotId})`);
  seen.set(k, s.slotId);
}

// Team photos ↔ team.ts
for (const m of team) {
  const p = photos[m.photo];
  if (!p) bad(m.photo, "team photo not in manifest");
  else if (p.alt !== portraitAlt(m)) bad(m.photo, "alt text differs from team.ts");
}

// No AI image tools in the project.
const pkg = JSON.parse(readFileSync("package.json", "utf8"));
for (const dep of Object.keys({ ...pkg.dependencies, ...pkg.devDependencies })) if (AI_PACKAGES.test(dep)) problems.push(`package.json: AI tool "${dep}" is not allowed`);

if (problems.length) {
  console.error(`images:verify — ${problems.length} problem(s):\n  ${problems.join("\n  ")}`);
  process.exit(1);
}
const filled = slots.filter((s) => photos[s.currentImage]).length;
console.log(`images:verify — OK: ${Object.keys(photos).length} photos in the manifest; ${filled}/${slots.length} slots filled, ${slots.length - filled} on the fallback tile`);
