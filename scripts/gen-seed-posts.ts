/**
 * Generates supabase/migrations/0003_seed_posts.sql from the legacy posts in src/data/blog.ts.
 * Run: npx tsx scripts/gen-seed-posts.ts
 */
import { writeFileSync } from "node:fs";
import { generateHTML } from "@tiptap/html/server";
import { posts } from "../src/data/blog";
import { blogExtensions } from "../src/lib/content/extensions";
import { textToTiptap } from "../src/lib/content/from-text";
import { htmlToText, readingMinutes, sanitizeBlogHtml } from "../src/lib/content/sanitize";

const cityFor: Record<string, string> = {
  "48-hours-in-kanpur": "kanpur",
  "eating-through-arya-nagar": "kanpur",
  "mills-that-built-a-city": "kanpur",
};
const tagsFor: Record<string, string[]> = {
  "48-hours-in-kanpur": ["itineraries", "first-timers", "heritage"],
  "eating-through-arya-nagar": ["food", "street-food"],
  "mills-that-built-a-city": ["history", "industry"],
};

// Dollar-quoting avoids any escaping problems with apostrophes in the copy.
const q = (s: string) => `$kkk$${s}$kkk$`;

const rows = posts.map((p) => {
  const doc = textToTiptap(p.body);
  const html = sanitizeBlogHtml(generateHTML(doc, blogExtensions));
  const minutes = readingMinutes(htmlToText(html));
  const tags = `array[${tagsFor[p.slug].map((t) => `'${t}'`).join(", ")}]::text[]`;
  return `(${q(p.slug)}, ${q(p.title)}, ${q(p.excerpt)}, ${q(JSON.stringify(doc))}::jsonb, ${q(html)}, ${q(p.image)}, ${q(p.alt)}, '${cityFor[p.slug]}', ${tags}, ${q(p.title)}, ${q(p.description)}, 'published', '${p.date}T06:00:00+05:30', ${minutes})`;
});

const sql = `-- Seeds the three original stories as published posts. Safe to re-run (upsert by slug).
-- Generated by scripts/gen-seed-posts.ts — do not edit by hand.
insert into public.posts
  (slug, title, excerpt, content_json, content_html, cover_url, cover_alt, city, tags, seo_title, seo_description, status, published_at, reading_minutes)
values
  ${rows.join(",\n  ")}
on conflict (slug) do update set
  title = excluded.title, excerpt = excluded.excerpt, content_json = excluded.content_json,
  content_html = excluded.content_html, cover_url = excluded.cover_url, cover_alt = excluded.cover_alt,
  city = excluded.city, tags = excluded.tags, seo_title = excluded.seo_title,
  seo_description = excluded.seo_description, status = excluded.status,
  published_at = excluded.published_at, reading_minutes = excluded.reading_minutes;
`;
writeFileSync("supabase/migrations/0003_seed_posts.sql", sql);
console.log(`wrote ${rows.length} posts`);
